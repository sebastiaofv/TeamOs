import { test, expect, type Page } from '@playwright/test';
import { readSavedBoard, selectTableView, toggleLanguage, confirmCsvExport } from '../support/portfolio';
import { seedControlProject as seed, controlKinds as kinds, controlLabels as labels } from '../support/control';

const table = (page: Page) => page.locator('.control-table');
const filterPanel = (page: Page) => page.getByRole('dialog', { name: 'Filters', exact: true });
async function openFilters(page: Page, kind: string) {
    await page.locator(`#portfolioFiltersBtn-control-${kind}`).click();
}

for (const kind of kinds) test(`${labels[kind]} paginates, selects by page, filters and exports all matching records`, async ({ page }) => {
    await seed(page, true, true);
    await page.getByRole('tab', { name: labels[kind], exact: true }).click();
    const scope = `control-${kind}`;
    await expect(table(page).locator('tbody tr')).toHaveCount(50);
    await page.locator(`#tablePageSize-${scope}`).selectOption('25');
    await table(page).getByRole('checkbox', { name: 'Select this page', exact: true }).check();
    await expect(page.locator('.portfolio-control .table-counts')).toContainText('25 selected');
    await page.locator(`#tableNextPage-${scope}`).click();
    await expect(table(page).locator('tbody tr')).toHaveCount(25);
    await expect(table(page).locator('tbody input:checked')).toHaveCount(0);
    await table(page).getByRole('checkbox', { name: 'Select this page', exact: true }).check();
    await expect(page.locator('.portfolio-control .table-counts')).toContainText('50 selected');
    await openFilters(page, kind);
    await filterPanel(page).getByLabel('Responsible', { exact: true }).selectOption('Ana Silva');
    await page.keyboard.press('Escape');
    await expect(page.locator('.portfolio-control .table-counts')).toContainText('30 of 60 records');
    await expect(page.locator('.portfolio-control .table-pagination')).toContainText('Page 1 of 2');
    await expect(page.locator(`#portfolioFiltersBtn-${scope}`)).toHaveAccessibleName('Filters, 1 active');
    await page.locator(`#tableColumns-${scope} summary`).click();
    await page.locator(`.table-column-panel [data-column-choice="status"]`).getByRole('button', { name: /^Hide / }).click();
    await page.keyboard.press('Escape');
    await expect(table(page).locator('th[data-column=status]')).toHaveCount(0);
    await page.locator(`#tableExportCsv-${scope}`).click();
    await expect(page.getByRole('alertdialog', { name: 'Export CSV' })).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.locator(`#tableExportCsv-${scope}`)).toBeFocused();
    await page.locator(`#tableExportCsv-${scope}`).click();
    const downloadPromise = page.waitForEvent('download');
    await confirmCsvExport(page, ';');
    const download = await downloadPromise;
    expect(download.suggestedFilename()).toBe(`Atlas-control-${kind}.csv`);
    const stream = await download.createReadStream();
    let csv = '';
    for await (const chunk of stream!) csv += chunk.toString();
    expect(csv.split('\r\n')).toHaveLength(31);
    expect(csv).toContain(`${kind} record 30`);
    expect(csv).not.toContain(`${kind} record 31`);
    expect(csv.split('\r\n')[0]).toMatch(/^ID;Title;Responsible;/);
    await page.getByRole('button', { name: 'Title', exact: true }).click();
    await page.getByRole('button', { name: 'Title', exact: true }).click();
    await expect(table(page).locator('tbody tr').first()).toContainText(`${kind} record 30`);
    await page.getByRole('button', { name: /Remove filter Responsible: Ana Silva/ }).click();
    await expect(page.locator('.portfolio-control .table-counts')).toContainText('60 of 60 records');
    await page.getByRole('button', { name: 'Clear selection', exact: true }).click();
    await expect(page.locator('.portfolio-control .table-counts')).not.toContainText('selected');
    expect(await page.evaluate(() => window.__portfolioTestWrites)).toEqual([]);
});

test('column preferences are scoped per control type, persist across reload and leave All columns independent', async ({ page }) => {
    await seed(page);
    await page.locator('#tableColumns-control-risks summary').click();
    await expect(page.locator('#tableColumns-control-risks [data-column-choice=id] .table-column-lock')).toBeVisible();
    await expect(page.locator('#tableColumns-control-risks [data-column-choice=title] .table-column-lock')).toBeVisible();
    await page.locator('.table-column-panel [data-column-choice="owner"]').getByRole('button', { name: /^Hide / }).click();
    await page.locator('.table-column-panel [data-column-choice="assignees"]').getByRole('button', { name: /^Show / }).click();
    await page.locator('#tableColumns-control-risks').getByRole('button', { name: 'Move Participants up', exact: true }).click();
    const projectId = (await readSavedBoard(page, 'control')).extensions.project.id;
    const preferenceKey = `teamos-kanban.workitems-table.columns.v1.${projectId}.control-risks`;
    const columns = await page.evaluate(key => localStorage.getItem(key), preferenceKey);
    await page.keyboard.press('Escape');
    await page.getByRole('tab', { name: 'Decisions', exact: true }).click();
    await expect(table(page).locator('th[data-column=owner]')).toHaveCount(1);
    await page.getByRole('tab', { name: 'Risks', exact: true }).click();
    await expect(table(page).locator('th[data-column=owner]')).toHaveCount(0);
    await page.locator('[data-view-mode=table]').click();
    await selectTableView(page, 'hierarchy');
    await expect(page.locator('#workitemsTable th[data-column=assignees]')).toHaveCount(1);
    expect(await page.evaluate(() => localStorage.getItem('teamos-kanban.workitems-table.columns.v1'))).toBeNull();
    await page.reload();
    await seed(page);
    expect(await page.evaluate(key => localStorage.getItem(key), preferenceKey)).toBe(columns);
    await expect(table(page).locator('th[data-column=owner]')).toHaveCount(0);
    await page.locator('#tableColumns-control-risks summary').click();
    await page.getByRole('button', { name: 'Reset to default', exact: true }).click();
    await page.keyboard.press('Escape');
    await expect(table(page).locator('th[data-column=owner]')).toHaveCount(1);
    expect(await page.evaluate(() => window.__portfolioTestWrites)).toEqual([]);
});

test('read-only consultation supports localized date filters, active tags and keyboard menus at 320px', async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 800 });
    await seed(page, false);
    await toggleLanguage(page);
    await page.getByRole('tab', { name: 'Decisões', exact: true }).click();
    await page.locator('#portfolioFiltersBtn-control-decisions').focus();
    await page.keyboard.press('Enter');
    const panel = page.getByRole('dialog', { name: 'Filtros', exact: true });
    await panel.getByLabel('Data da decisão', { exact: true }).fill('25/10/2026');
    await page.keyboard.press('Escape');
    await expect(page.locator('#portfolioFiltersBtn-control-decisions')).toBeFocused();
    await expect(page.locator('.portfolio-control .portfolio-active-filters')).toContainText('25/10/2026');
    await expect(table(page).locator('tbody tr')).toHaveCount(2);
    await expect(page.getByRole('button', { name: 'Novo registo', exact: true })).toBeDisabled();
    await page.locator('#tableColumns-control-decisions summary').click();
    const chooser = page.locator('.portfolio-control .table-column-panel');
    const box = await chooser.boundingBox();
    expect(box!.x).toBeGreaterThanOrEqual(0);
    expect(box!.x + box!.width).toBeLessThanOrEqual(320);
    await page.keyboard.press('Escape');
    await expect(page.locator('#tableColumns-control-decisions summary')).toBeFocused();
    await table(page).locator('tbody input').first().check();
    await page.getByRole('button', { name: 'Choose supported runtime', exact: true }).click();
    await expect(page.locator('.control-modal').getByRole('button', { name: 'Editar', exact: true })).toHaveCount(0);
    await page.keyboard.press('Escape');
    await page.getByLabel('Pesquisar por ID ou título', { exact: true }).fill('missing');
    await expect(page.locator('.control-empty')).toBeVisible();
    await expect(page.locator('#tableExportCsv-control-decisions')).toBeDisabled();
    await page.locator('.control-empty').getByRole('button', { name: 'Limpar filtros', exact: true }).click();
    await expect(table(page).locator('tbody tr')).toHaveCount(2);
    await expect(page.locator('.portfolio-control .portfolio-active-filters')).toHaveCount(0);
    expect(await page.evaluate(() => window.__portfolioTestWrites)).toEqual([]);
});
