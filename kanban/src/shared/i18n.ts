const translations: Record<Language, Record<TranslationKey, string>> = { en, pt };

export const DEFAULT_LANGUAGE: Language = 'en';
export const LANGUAGE_CODES: Record<Language, string> = { en: 'EN', pt: 'PT' };

export function normalizeLanguage(value: unknown): Language {
    return value === 'pt' ? 'pt' : DEFAULT_LANGUAGE;
}

export function readStoredLanguage(): Language {
    try {
        return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));
    } catch (_) {
        return DEFAULT_LANGUAGE;
    }
}

export function translate(language: Language, key: TranslationKey, values: TranslationValues = {}): string {
    const template = translations[language][key] || translations[DEFAULT_LANGUAGE][key] || key;
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

// Timeline summaries are saved in the project file in English; the timeline
// panel shows their fixed wording in the selected language (timelineEventText).
export function translateTimeline(key: TranslationKey, values: TranslationValues = {}): string {
    return translate('en', key, values);
}

export function translateCurrent(key: TranslationKey, values: TranslationValues = {}): string {
    return translate(useAppStore.getState().activeLanguage, key, values);
}

export function getCalendarMonthName(language: Language, month: number): string {
    return new Intl.DateTimeFormat(language === 'pt' ? 'pt-PT' : 'en-US', { month: 'long', timeZone: 'UTC' })
        .format(new Date(Date.UTC(2020, month, 1)));
}

export function getCalendarWeekdayName(language: Language, weekday: number, short = false): string {
    return new Intl.DateTimeFormat(language === 'pt' ? 'pt-PT' : 'en-US', {
        weekday: short ? 'short' : 'long',
        timeZone: 'UTC'
    }).format(new Date(Date.UTC(2020, 0, 5 + weekday)));
}

export function getCalendarMonthLabel(language: Language, year: number, month: number): string {
    return `${getCalendarMonthName(language, month)} ${year}`;
}

const PLANNER_DATE_FORMATS: Record<'long' | 'medium' | 'short', Intl.DateTimeFormatOptions> = {
    long: { weekday: 'long', day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' },
    medium: { weekday: 'short', day: 'numeric', month: 'short', timeZone: 'UTC' },
    short: { weekday: 'short', day: 'numeric', timeZone: 'UTC' }
};

// "Friday, 25 Sep 2026" (long), "Fri 25 Sep" (medium) or "Fri 25" (short) for a YYYY-MM-DD date.
export function formatPlannerDateLabel(language: Language, isoDate: string, style: 'long' | 'medium' | 'short' = 'long'): string {
    const [year, month, day] = isoDate.split('-').map(Number);
    if (!year || !month || !day) return isoDate;
    const options = PLANNER_DATE_FORMATS[style];
    return new Intl.DateTimeFormat(language === 'pt' ? 'pt-PT' : 'en-GB', options).format(new Date(Date.UTC(year, month - 1, day)));
}

export function getCurrentLanguage(): Language {
    return useAppStore.getState().activeLanguage;
}

export function useI18n() {
    const language = useAppStore((state) => state.activeLanguage);

    const setLanguage = useCallback((next: Language) => {
        const activeLanguage = normalizeLanguage(next);
        useAppStore.setState({ activeLanguage });
        document.documentElement.lang = activeLanguage === 'pt' ? 'pt-PT' : 'en';
        try {
            localStorage.setItem(LANGUAGE_STORAGE_KEY, activeLanguage);
        } catch (_) { }
    }, []);

    const toggleLanguage = useCallback(() => {
        setLanguage(language === 'en' ? 'pt' : 'en');
    }, [language, setLanguage]);

    const t = useCallback((key: TranslationKey, values?: TranslationValues) => translate(language, key, values), [language]);

    return {
        language,
        languageCode: LANGUAGE_CODES[language],
        setLanguage,
        toggleLanguage,
        t
    };
}

export function useInitializeLanguage(): void {
    useLayoutEffect(() => {
        const language = readStoredLanguage();
        useAppStore.setState({ activeLanguage: language });
        document.documentElement.lang = language === 'pt' ? 'pt-PT' : 'en';
    }, []);
}

export type { TranslationKey, TranslationValues };
